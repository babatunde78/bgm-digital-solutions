'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const uuid = '10000000-0000-4000-8000-000000000001';
test('staff interface signs in, loads a basis-selected schedule and clears sensitive state on logout', async () => {
  const dom = new JSDOM(fs.readFileSync('campus/web/index.html', 'utf8'), { url: 'http://127.0.0.1:8787', runScripts: 'outside-only' });
  const { window } = dom; const calls = []; let receiptAttempts=0;let stageAttempts=0;let pendingStage;
  window.fetch = async (url, options) => {
    const body = options ? JSON.parse(options.body) : null; calls.push({ url, body, options });
    if (url === '/api/config') return { ok: true, json: async () => ({ productName: 'Synthetic <Campus>' }) };
    if (url === '/api/login') return { ok: true, json: async () => ({ data: { access_token: 'synthetic.token', expires_in: 3600 } }) };
    if (url === '/api/logout') return { ok: true };
    if(body.action==='submit_revenue'||body.action==='submit_rules') return {ok:true,json:async()=>({data:2})};
    if(body.action==='correction'||body.action==='submit_reversal') return {ok:true,json:async()=>({data:1})};
    if(body.action==='prepare_batch')return{ok:true,json:async()=>({data:1})};
    if(body.action==='stage_import'){
      stageAttempts++;
      if(stageAttempts===2)return new Promise(resolve=>{pendingStage=()=>resolve({ok:true,json:async()=>({data:{batch_id:uuid,status:'staged',version:1,row_count:1,error_count:0,total_gross_minor:'100',total_fee_minor:'0',total_net_minor:'100'}})});});
      return{ok:true,json:async()=>({data:{batch_id:body.payload.batch_id,status:'staged',version:1,row_count:1,error_count:0,total_gross_minor:'100',total_fee_minor:'0',total_net_minor:'100'}})};
    }
    if(body.action==='reconciliation'||body.action==='reconciliation_transition')return{ok:true,json:async()=>({data:1})};
    if(['tolerance','settlement','settlement_reversal','settlement_transition'].includes(body.action))return{ok:true,json:async()=>({data:1})};
    if(['budget_event','budget_line','budget_fund','budget_transition'].includes(body.action))return{ok:true,json:async()=>({data:1})};
    if(body.action==='budgets')return{ok:true,json:async()=>({data:{period_id:uuid,basis:'accrual',as_of:'2026-11-10',refreshed_at:'2026-11-10T10:00:00Z',lines:[],events:[],unattributed_lines:[{journal_id:uuid,line_no:1,account_id:uuid,unattributed_minor:'20000'}]}})};
    if(body.action==='candidates')return{ok:true,json:async()=>({data:[{id:uuid,kind:'receipt',document_date:'2026-11-08',reference:'000001',available_minor:'100',suggestion:'exact_reference_and_amount'}]})};
    if(body.action==='billing_preview')return{ok:true,json:async()=>({data:{rows:[{student_id:uuid,errors:[]}],totals:{student_count:1,line_count:1,total_minor:'100'}}})};
    if(body.action==='receipt') {
      receiptAttempts++;
      return receiptAttempts===1?{ok:false,status:503,json:async()=>({error:'Synthetic uncertain response'})}:{ok:true,json:async()=>({data:1})};
    }
    const data = body.action === 'configuration' ? { accounts: [{ id: uuid, code: '0010', name: '<Synthetic cash>', account_type: 'asset' }], periods: [], policies: [] } :
      body.action === 'context' ? { platform_administrator: false, institutions: [{ id: uuid, name: '<Synthetic University>', currency: 'NGN', role: 'bursar' }] } :
      [{ id: uuid, posted_on: '2026-11-08', basis: 'cash', status: 'posted', version: 5, reversal_of: null }];
    return { ok: true, json: async () => ({ data }) };
  };
  const settle = () => new Promise(resolve => setImmediate(resolve));
  try {
    window.eval(fs.readFileSync('campus/web/client.js', 'utf8'));
    const document = window.document;
    document.querySelector('[name=email]').value = 'synthetic@example.invalid';
    document.querySelector('[name=password]').value = 'synthetic-password';
    document.getElementById('login').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true }));
    await settle();
    assert.equal(document.getElementById('workspace').hidden, false);
    assert.equal(document.querySelector('[name=password]').value, '');
    assert.equal(document.getElementById('product-name').textContent, 'Synthetic <Campus>');
    assert.equal(document.getElementById('product-name').children.length, 0);
    const select = document.getElementById('institution'); select.value = uuid; select.dispatchEvent(new window.Event('change'));
    document.getElementById('refresh').click(); await settle();
    assert.equal(document.querySelectorAll('#journals tr').length, 1);
    assert.deepEqual(calls.at(-1).body, { action: 'schedule', payload: { institution_id: uuid, basis: 'cash' } });
    document.getElementById('refresh-configuration').click(); await settle();
    assert.equal(document.getElementById('configuration-bursar').hidden, false);
    assert.equal(document.getElementById('configuration-admin').hidden, true);
    assert.match(document.getElementById('configuration-output').textContent, /<Synthetic cash>/);
    assert.equal(document.querySelectorAll('#configuration-output synthetic').length, 0);
    const manual=document.getElementById('revenue_manual'); manual.elements.namedItem('event_id').value=uuid; manual.elements.namedItem('expected_version').value='1';
    for(const fieldset of manual.querySelectorAll('[data-plan-basis]')) {
      fieldset.querySelector('[data-plan-policy]').value=uuid;
      const treatment=fieldset.querySelector('[data-plan-treatment]'); treatment.value='nonrecognition'; treatment.dispatchEvent(new window.Event('change'));
      fieldset.querySelector('[data-plan-reason]').value='Synthetic explicit decision for UI testing only';
    }
    manual.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true})); await settle();
    assert.equal(calls.at(-1).body.action,'submit_revenue');
    assert.deepEqual(calls.at(-1).body.payload.plans.map(plan=>plan.basis),['cash','accrual']);
    const automatic=document.getElementById('revenue_automatic');
    for(const name of ['event_id','cash_rule_id','accrual_rule_id']) automatic.elements.namedItem(name).value=uuid;
    automatic.elements.namedItem('expected_version').value='1';
    automatic.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.equal(calls.at(-1).body.action,'submit_rules');
    const receipt=document.getElementById('receipt');
    for(const [name,value] of Object.entries({student_id:uuid,period_id:uuid,document_date:'2026-11-09',reference:'000001',amount_minor:'100'})) receipt.elements.namedItem(name).value=value;
    receipt.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    const candidate=calls.at(-1).body.payload.event_id;
    assert.equal(typeof candidate,'string');
    receipt.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.equal(calls.at(-1).body.payload.event_id,candidate);
    const correction=document.getElementById('correction');
    for(const[name,value]of Object.entries({kind:'refund',original_id:uuid,period_id:uuid,document_date:'2027-01-10',amount_minor:'100',reason:'Synthetic correction'})) correction.elements.namedItem(name).value=value;
    correction.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.equal(calls.at(-1).body.action,'correction');
    assert.equal(calls.at(-1).body.payload.kind,'refund');
    const reversal=document.getElementById('submit_reversal');reversal.elements.namedItem('event_id').value=uuid;reversal.elements.namedItem('expected_version').value='1';
    reversal.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.deepEqual(calls.at(-1).body,{action:'submit_reversal',payload:{institution_id:uuid,event_id:uuid,expected_version:1}});
    const batch=document.getElementById('prepare_batch');
    for(const[name,value]of Object.entries({fee_id:uuid,period_id:uuid,document_date:'2026-11-08',student_ids:uuid}))batch.elements.namedItem(name).value=value;
    document.getElementById('preview-billing').click();await settle();
    assert.deepEqual(calls.at(-1).body,{action:'billing_preview',payload:{institution_id:uuid,fee_id:uuid,period_id:uuid,document_date:'2026-11-08',student_ids:[uuid]}});
    assert.match(document.getElementById('billing-preview-output').textContent,/100/);
    batch.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.equal(calls.at(-1).body.action,'prepare_batch');
    assert.equal(typeof calls.at(-1).body.payload.batch_id,'string');
    const stage=document.getElementById('stage_import');
    const csv='transaction_id,date,reference,direction,currency,gross_minor,fee_minor,net_minor\n000001,2026-11-09,000001,credit,NGN,100,0,100';
    stage.elements.namedItem('bank_source_id').value=uuid;stage.elements.namedItem('csv').value=csv;
    stage.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.equal(calls.at(-1).body.action,'stage_import');assert.equal(calls.at(-1).body.payload.column_map.date,'date');
    assert.match(document.getElementById('message').textContent,/No journals were posted/);
    const matching=document.getElementById('reconciliation');matching.elements.namedItem('description').value='Synthetic reviewed group';
    document.getElementById('add-matching-pair').click();
    for(const input of document.querySelectorAll('#matching-pairs input'))input.value=input.dataset.revenueField==='amount_minor'?'100':uuid;
    matching.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.deepEqual(calls.at(-1).body.payload.pairs,[{bank_line_id:uuid,event_id:uuid,amount_minor:'100'}]);
    const lookup=document.getElementById('candidate_lookup');lookup.elements.namedItem('bank_line_id').value=uuid;
    lookup.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.match(document.getElementById('candidate-output').textContent,/exact_reference_and_amount/);
    const tolerance=document.getElementById('tolerance');
    for(const[name,value]of Object.entries({bank_line_id:uuid,side:'bank',event_id:'',amount_minor:'10',cash_profile_id:uuid,accrual_profile_id:uuid,reason:'Synthetic explicit bank difference'}))tolerance.elements.namedItem(name).value=value;
    tolerance.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.equal(calls.at(-1).body.action,'tolerance');assert.equal(calls.at(-1).body.payload.event_id,null);assert.equal(calls.at(-1).body.payload.amount_minor,'10');
    const settlement=document.getElementById('settlement');
    for(const[name,value]of Object.entries({bank_line_id:uuid,period_id:uuid,document_date:'2026-11-10',cash_profile_id:uuid,accrual_profile_id:uuid}))settlement.elements.namedItem(name).value=value;
    settlement.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.equal(calls.at(-1).body.action,'settlement');const originalSettlement=calls.at(-1).body.payload.settlement_id;
    const settlementReversal=document.getElementById('settlement_reversal');
    for(const[name,value]of Object.entries({original_id:originalSettlement,period_id:uuid,document_date:'2027-01-11',reason:'Synthetic exact backout'}))settlementReversal.elements.namedItem(name).value=value;
    settlementReversal.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.equal(calls.at(-1).body.action,'settlement_reversal');assert.equal(calls.at(-1).body.payload.original_id,originalSettlement);
    const budget=document.getElementById('budget_event');
    for(const[name,value]of Object.entries({budget_id:uuid,kind:'actual',document_date:'2026-11-10',amount_minor:'20000',description:'Synthetic actual',journal_id:uuid,line_no:'1',commitment_id:uuid}))budget.elements.namedItem(name).value=value;
    budget.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.equal(calls.at(-1).body.action,'budget_event');assert.equal(calls.at(-1).body.payload.amount_minor,'20000');
    assert.deepEqual(calls.at(-1).body.payload.details,{journal_id:uuid,line_no:1,commitment_id:uuid,description:'Synthetic actual'});
    const budgetView=document.getElementById('budget_view');
    for(const[name,value]of Object.entries({period_id:uuid,basis:'accrual',as_of:'2026-11-10'}))budgetView.elements.namedItem(name).value=value;
    budgetView.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    assert.deepEqual(calls.at(-1).body,{action:'budgets',payload:{institution_id:uuid,period_id:uuid,basis:'accrual',as_of:'2026-11-10'}});
    assert.match(document.getElementById('budget-output').textContent,/20000/);
    assert.equal(window.localStorage.length, 0);
    assert.equal(window.sessionStorage.length, 0);
    assert.equal(document.cookie, '');
    stage.elements.namedItem('bank_source_id').value=uuid;stage.elements.namedItem('csv').value=csv;
    stage.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await settle();
    document.getElementById('logout').click(); await settle();pendingStage();await settle();
    assert.equal(document.getElementById('workspace').hidden, true);
    assert.equal(document.querySelectorAll('#journals tr').length, 0);
    assert.equal(document.getElementById('configuration-output').children.length, 0);
    assert.equal(document.getElementById('billing-preview-output').children.length,0);
    assert.equal(document.getElementById('candidate-output').children.length,0);
    assert.equal(document.getElementById('settlement-output').children.length,0);
    assert.equal(document.getElementById('budget-output').children.length,0);
    assert.equal(document.getElementById('message').textContent,'Local session cleared.');
    assert.equal(calls.at(-1).options.headers.Authorization, 'Bearer synthetic.token');
  } finally { window.close(); }
});
